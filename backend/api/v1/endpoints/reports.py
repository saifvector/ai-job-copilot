"""
Reporting & Export Center API Endpoints for Phase 9.
Provides routes to generate, list, preview, and download professional reports
and datasets across PDF, CSV, XLSX, and JSON formats.
"""
import uuid
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import FileResponse

from core.dependencies import get_current_user_id, get_report_service
from schemas.common import ApiResponse
from schemas.report import (
    ReportGenerateRequest,
    ReportListResponse,
    ReportListStats,
    ReportResponse,
)
from services.report_service import ReportService

router = APIRouter()


@router.post(
    "/generate",
    response_model=ApiResponse[ReportResponse],
    status_code=status.HTTP_201_CREATED,
    summary="Generate and Export Report",
    description="Generate publication-grade report in PDF, CSV, XLSX, or JSON format.",
)
async def generate_report(
    payload: ReportGenerateRequest,
    user_id: uuid.UUID = Depends(get_current_user_id),
    service: ReportService = Depends(get_report_service),
) -> ApiResponse[ReportResponse]:
    try:
        report = await service.generateReport(user_id=user_id, request=payload)
        resp_data = ReportResponse.model_validate(report)
        resp_data.download_url = f"/api/v1/reports/{report.id}/download"
        return ApiResponse(
            data=resp_data,
            message=f"{report.title} successfully generated in {report.format} format.",
        )
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(exc),
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Report generation failed: {str(exc)}",
        )


@router.get(
    "",
    response_model=ApiResponse[ReportListResponse],
    summary="List Generated Reports",
    description="Retrieve all reports generated by candidate with aggregate storage and download statistics.",
)
async def list_reports(
    report_type: Optional[str] = Query(None, description="Filter by report type: APPLICATION_REPORT, MATCH_REPORT, SKILL_REPORT, CAREER_REPORT, RESUME_REPORT"),
    format: Optional[str] = Query(None, description="Filter by format: PDF, CSV, XLSX, JSON"),
    user_id: uuid.UUID = Depends(get_current_user_id),
    service: ReportService = Depends(get_report_service),
) -> ApiResponse[ReportListResponse]:
    reports, stats_dict = await service.listReports(
        user_id=user_id,
        report_type=report_type,
        export_format=format,
    )

    report_items = []
    for r in reports:
        item = ReportResponse.model_validate(r)
        item.download_url = f"/api/v1/reports/{r.id}/download"
        report_items.append(item)

    stats = ReportListStats(
        total_reports=stats_dict.get("total_reports", 0),
        total_downloads=stats_dict.get("total_downloads", 0),
        storage_used_bytes=stats_dict.get("storage_used_bytes", 0),
        most_popular_type=stats_dict.get("most_popular_type"),
    )

    return ApiResponse(
        data=ReportListResponse(
            reports=report_items,
            stats=stats,
        )
    )


@router.get(
    "/{id}",
    response_model=ApiResponse[ReportResponse],
    summary="Get Report Metadata",
    description="Retrieve report details and download link by ID.",
)
async def get_report_by_id(
    id: uuid.UUID,
    user_id: uuid.UUID = Depends(get_current_user_id),
    service: ReportService = Depends(get_report_service),
) -> ApiResponse[ReportResponse]:
    report = await service.getReportById(report_id=id, user_id=user_id)
    if not report:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Report with ID '{id}' was not found.",
        )
    resp_data = ReportResponse.model_validate(report)
    resp_data.download_url = f"/api/v1/reports/{report.id}/download"
    return ApiResponse(data=resp_data)


@router.get(
    "/{id}/download",
    summary="Download Generated Report File",
    description="Download the report file directly (PDF, CSV, XLSX, JSON) with attachment disposition header.",
)
async def download_report_file(
    id: uuid.UUID,
    user_id: uuid.UUID = Depends(get_current_user_id),
    service: ReportService = Depends(get_report_service),
):
    try:
        file_path, file_name, media_type = await service.downloadReport(
            report_id=id,
            user_id=user_id,
        )
        return FileResponse(
            path=file_path,
            filename=file_name,
            media_type=media_type,
            headers={
                "Content-Disposition": f'attachment; filename="{file_name}"',
            },
        )
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc))
    except FileNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc))


@router.delete(
    "/{id}",
    response_model=ApiResponse[bool],
    summary="Delete Generated Report",
    description="Remove a report record and delete its exported file from disk.",
)
async def delete_report(
    id: uuid.UUID,
    user_id: uuid.UUID = Depends(get_current_user_id),
    service: ReportService = Depends(get_report_service),
) -> ApiResponse[bool]:
    deleted = await service.deleteReport(report_id=id, user_id=user_id)
    if not deleted:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Report '{id}' not found or could not be removed.",
        )
    return ApiResponse(
        data=True,
        message="Report successfully removed.",
    )
